//! Reader for VCD (Value Change Dump, IEEE 1364) files: the text format of
//! logic analyzers (sigrok/PulseView, Saleae), mixed-signal oscilloscopes and
//! Verilog simulators.
//!
//! ```text
//! $timescale 1 ns $end
//! $scope module top $end
//! $var wire 1 ! clk $end        1-bit signal, identifier "!"
//! $var real 64 " vout $end      analog value
//! $var wire 8 # data $end       bus (8 bits)
//! $upscope $end
//! $enddefinitions $end
//! #0                            time (in timescale units)
//! 0!                            clk = 0
//! r1.25 "                       vout = 1.25
//! #50
//! 1!
//! ```
//!
//! - 1-bit signals become digital traces (0/1; `x` and `z` are shown as
//!   0.5), drawn as steps.
//! - `real` variables become analog traces (volts).
//! - Buses (more than 1 bit, values `b0101 #`) become bus traces: the value
//!   as a number, NaN if a bit is `x` or `z`.

use super::{Confidence, Format, ReadError, nice_per_div};
use crate::model::{Acquisition, Capture, Display, Samples, Source, Trace, TraceId, Unit};

/// VCD.
pub struct VcdFormat;

impl Format for VcdFormat {
    fn name(&self) -> &'static str {
        "VCD (logic analyzer / simulator)"
    }

    fn probe(&self, bytes: &[u8]) -> Confidence {
        let head = String::from_utf8_lossy(&bytes[..bytes.len().min(64 * 1024)]);
        let starts = head.trim_start().starts_with('$');
        if starts && head.contains("$var") && head.contains("$enddefinitions") {
            Confidence::Sure
        } else if starts && head.contains("$var") {
            Confidence::Likely
        } else {
            Confidence::No
        }
    }

    fn read(&self, bytes: &[u8]) -> Result<Capture, ReadError> {
        read(bytes)
    }
}

/// One variable of the file.
struct Var {
    name: String,
    real: bool,
    /// Bits of a bus; `None` for a 1-bit signal or a real.
    bus: Option<u16>,
    /// Changes: (time in timescale units, value).
    changes: Vec<(u64, f64)>,
}

/// Seconds of one timescale unit: "1 ns", "10ps", "100 us".
fn timescale(text: &str) -> Option<f64> {
    let t: String = text.split_whitespace().collect();
    let digits: String = t.chars().take_while(char::is_ascii_digit).collect();
    let n: f64 = digits.parse().ok()?;
    let unit = match &t[digits.len()..] {
        "s" => 1.0,
        "ms" => 1e-3,
        "us" => 1e-6,
        "ns" => 1e-9,
        "ps" => 1e-12,
        "fs" => 1e-15,
        _ => return None,
    };
    Some(n * unit)
}

/// The value of a 1-bit scalar: 0, 1, or 0.5 for x / z / others.
fn bit(c: char) -> f64 {
    match c {
        '0' => 0.0,
        '1' => 1.0,
        _ => 0.5,
    }
}

/// The value of a vector `0101`, `x01`: a number, NaN if a bit is x or z.
/// A short vector is extended to the left with 0, or with x / z if its first
/// bit is x / z (IEEE 1364).
fn vector(bits: &str) -> f64 {
    let mut v = 0.0;
    for c in bits.chars() {
        v = match c {
            '0' => v * 2.0,
            '1' => v * 2.0 + 1.0,
            _ => return f64::NAN,
        };
    }
    v
}

/// The maker in a `$version` text: "sigrok 0.5" → "sigrok",
/// "Generated by Wokwi.com" → "Wokwi".
fn vendor_of(version: &str) -> String {
    let words: Vec<&str> = version.split_whitespace().collect();
    let name = match words.iter().position(|w| w.eq_ignore_ascii_case("by")) {
        Some(i) => words.get(i + 1).copied(),
        None => words.first().copied(),
    };
    let name = name.unwrap_or("VCD").trim_end_matches(['.', ',']);
    // A web domain: keep the name only.
    let name = name
        .strip_suffix(".com")
        .or_else(|| name.strip_suffix(".org"))
        .unwrap_or(name);
    if name.is_empty() {
        "VCD".to_owned()
    } else {
        name.to_owned()
    }
}

/// Read a VCD file.
///
/// # Errors
/// A [`ReadError`] if there is no `$var` with values.
/// The most signals ($var) read from a file.
pub const MAX_VARS: usize = 4096;
/// The most value changes read from a file (each is drawn as up to two
/// points).
pub const MAX_CHANGES: usize = 20_000_000;

pub fn read(bytes: &[u8]) -> Result<Capture, ReadError> {
    let text = String::from_utf8_lossy(bytes);
    let mut tokens = text.split_whitespace().peekable();
    let mut vars: Vec<Var> = Vec::new();
    // identifier → index in `vars` (an identifier can be shared by several
    // $var lines; the first one is used).
    let mut ids: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
    let mut skipped_buses: Vec<String> = Vec::new();
    let mut unit_s = None;
    let mut version = String::new();
    let mut warnings = Vec::new();

    // Header: $keyword ... $end blocks until $enddefinitions.
    while let Some(tok) = tokens.next() {
        let mut block = || {
            let mut words = Vec::new();
            for w in tokens.by_ref() {
                if w == "$end" {
                    break;
                }
                words.push(w);
            }
            words
        };
        match tok {
            "$timescale" => unit_s = timescale(&block().join(" ")),
            "$version" => version = block().join(" "),
            "$var" => {
                let w = block();
                if w.len() < 4 {
                    continue;
                }
                let (kind, size, id) = (w[0], w[1], w[2]);
                // "data [7:0]": the bit range is part of the name.
                let name = w[3..].concat();
                let real = kind == "real" || kind == "realtime";
                let width: u16 = size.parse().unwrap_or(1);
                if !real && width > 64 {
                    skipped_buses.push(format!("{name} ({width} bits)"));
                    continue;
                }
                if !ids.contains_key(id) {
                    if vars.len() >= MAX_VARS {
                        return Err(ReadError(format!(
                            "VCD: more than {MAX_VARS} signals; this viewer shows at most {MAX_VARS}"
                        )));
                    }
                    ids.insert(id.to_owned(), vars.len());
                    vars.push(Var {
                        name,
                        real,
                        bus: (!real && width > 1).then_some(width),
                        changes: Vec::new(),
                    });
                }
            }
            "$enddefinitions" => {
                block();
                break;
            }
            t if t.starts_with('$') => {
                block();
            }
            _ => {}
        }
    }
    if vars.is_empty() {
        return Err(ReadError("VCD: no 1-bit or real variable".into()));
    }
    let unit_s = unit_s.unwrap_or_else(|| {
        warnings.push("no $timescale: 1 ns is used".to_owned());
        1e-9
    });
    if !skipped_buses.is_empty() {
        warnings.push(format!(
            "buses wider than 64 bits not shown: {}",
            skipped_buses.join(", ")
        ));
    }

    // Value changes.
    let mut now: u64 = 0;
    let mut end: u64 = 0;
    let mut total_changes = 0usize;
    while let Some(tok) = tokens.next() {
        if total_changes > MAX_CHANGES {
            return Err(ReadError(format!(
                "VCD: more than {MAX_CHANGES} value changes; cut the record shorter"
            )));
        }
        let mut set = |id: &str, v: f64, now: u64| {
            if let Some(&i) = ids.get(id) {
                let var = &mut vars[i];
                // A vector value of a 1-bit signal: x / z is 0.5.
                let v = if var.bus.is_none() && !var.real && v.is_nan() {
                    0.5
                } else {
                    v
                };
                let ch = &mut var.changes;
                // Keep one value per time: the last one.
                if ch.last().is_some_and(|c| c.0 == now) {
                    ch.pop();
                }
                // A digital value that does not change is not a change.
                let same = |a: f64| a == v || (a.is_nan() && v.is_nan());
                if !var.real && ch.last().is_some_and(|c| same(c.1)) {
                    return;
                }
                ch.push((now, v));
                total_changes += 1;
            }
        };
        let mut chars = tok.chars();
        match chars.next() {
            Some('#') => {
                now = chars.as_str().parse().unwrap_or(now);
                end = end.max(now);
            }
            Some('$') => {} // $dumpvars, $end, $dumpall…: the values follow as usual
            Some(c @ ('0' | '1' | 'x' | 'X' | 'z' | 'Z')) => set(chars.as_str(), bit(c), now),
            Some('b' | 'B') => {
                if let Some(id) = tokens.next() {
                    set(id, vector(chars.as_str()), now);
                }
            }
            Some('r' | 'R') => {
                let v: f64 = chars.as_str().parse().unwrap_or(f64::NAN);
                if let Some(id) = tokens.next() {
                    set(id, v, now);
                }
            }
            _ => {}
        }
    }

    let mut traces = Vec::new();
    let mut digital = 0u16;
    for var in vars {
        if var.changes.is_empty() {
            continue;
        }
        let t = |u: u64| u as f64 * unit_s;
        let mut points: Vec<[f64; 2]> = Vec::with_capacity(var.changes.len() * 2 + 1);
        for (k, &(time, v)) in var.changes.iter().enumerate() {
            // Digital: a step (the old value up to the change, then the new one).
            if !var.real && k > 0 {
                points.push([t(time), var.changes[k - 1].1]);
            }
            points.push([t(time), v]);
        }
        // Hold the last value until the end of the record.
        if let Some(&(last_t, last_v)) = var.changes.last()
            && last_t < end
        {
            points.push([t(end), last_v]);
        }
        let trace = if var.real {
            let (lo, hi) = points
                .iter()
                .fold((f64::INFINITY, f64::NEG_INFINITY), |(lo, hi), p| {
                    (lo.min(p[1]), hi.max(p[1]))
                });
            // Analog numbers are u8: more than 255 real variables keep 255.
            Trace::new(
                TraceId::Analog(u8::try_from(traces.len() + 1).unwrap_or(u8::MAX)),
                var.name,
                Samples::Timed(points),
                Display {
                    per_div: nice_per_div(if hi > lo { hi - lo } else { 1.0 }),
                    zero_div: 0.0,
                    probe: 1.0,
                    coupling: None,
                },
            )
        } else {
            digital += 1;
            let mut tr = Trace::new(
                TraceId::Digital(digital),
                var.name,
                Samples::Timed(points),
                Display {
                    per_div: 1.0,
                    zero_div: 0.0,
                    probe: 1.0,
                    coupling: None,
                },
            );
            tr.unit = Unit::Logic;
            tr.resolution = Some(1.0);
            tr.bus = var.bus;
            tr
        };
        let mut trace = trace;
        trace.time_resolution = Some(unit_s);
        traces.push(trace);
    }
    if traces.is_empty() {
        return Err(ReadError("VCD: no value changes".into()));
    }
    let record_length = traces.iter().map(|t| t.samples.len()).max().unwrap_or(0);
    let span = end as f64 * unit_s;
    let vendor = vendor_of(&version);
    Ok(Capture {
        source: Source {
            vendor,
            model: String::new(),
            format: VcdFormat.name().into(),
        },
        traces,
        time_per_div: (span > 0.0).then_some(span / 10.0),
        screen: None,
        trigger: None,
        acquisition: Acquisition::RealTime {
            sample_rate_hz: 1.0 / unit_s,
        },
        record_length,
        warnings,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "$date today $end
$version sigrok 0.5 $end
$timescale 10 ns $end
$scope module logic $end
$var wire 1 ! clk $end
$var wire 1 \" en $end
$var real 64 # vout $end
$var wire 8 $ data $end
$upscope $end
$enddefinitions $end
#0
$dumpvars
0!
x\"
r0.5 #
b00000000 $
$end
#50
1!
1\"
r1.5 #
b10100101 $
#100
bx1 $
0!
#150
1!
r2.5 #
#200
0!
";

    #[test]
    fn reads_bits_reals_and_buses() {
        assert_eq!(VcdFormat.probe(SAMPLE.as_bytes()), Confidence::Sure);
        let w = read(SAMPLE.as_bytes()).unwrap();
        assert_eq!(w.source.vendor, "sigrok");
        let labels: Vec<&str> = w.traces.iter().map(|t| t.label.as_str()).collect();
        assert_eq!(labels, ["clk", "en", "vout", "data"]);
        assert!(w.warnings.is_empty(), "{:?}", w.warnings);
        let clk = &w.traces[0];
        assert!(clk.is_digital() && clk.unit == Unit::Logic);
        // Steps: at 500 ns the value goes from 0 to 1.
        assert_eq!(&clk.points()[..3], &[[0.0, 0.0], [5e-7, 0.0], [5e-7, 1.0]]);
        // en: unknown (x) shown as 0.5, then 1, held to the end (2 µs).
        let en = &w.traces[1];
        assert_eq!(en.points()[0], [0.0, 0.5]);
        assert_eq!(en.points().last(), Some(&[2e-6, 1.0]));
        let vout = &w.traces[2];
        assert!(!vout.is_digital());
        assert_eq!(vout.points()[1], [5e-7, 1.5]);
        assert_eq!(w.time_per_div, Some(2e-7));
        // data: 8-bit bus, 0, then 0xA5, then unknown, held to the end.
        let data = &w.traces[3];
        assert!(data.is_digital() && data.is_bus() && data.bus == Some(8));
        let p = data.points();
        assert_eq!(&p[..3], &[[0.0, 0.0], [5e-7, 0.0], [5e-7, 165.0]]);
        assert_eq!(p[3], [1e-6, 165.0]);
        assert!(p[4][1].is_nan() && p[4][0] == 1e-6);
        assert_eq!(p.last().unwrap()[0], 2e-6);
    }

    #[test]
    fn vectors() {
        assert_eq!(vector("10100101"), 165.0);
        assert_eq!(vector("1"), 1.0);
        assert!(vector("1x0").is_nan());
        assert!(vector("z").is_nan());
        // A 1-bit signal given as a vector, and a bus name with its range.
        let text = "$timescale 1 us $end
$var wire 1 ! a $end
$var reg 4 # cnt [3:0] $end
$enddefinitions $end
#0 b0 ! b0011 #
#1 bx ! b0011 # b1 #
#2 b1 !
";
        let w = read(text.as_bytes()).unwrap();
        assert_eq!(w.traces[1].label, "cnt[3:0]");
        let a = w.traces[0].points();
        assert_eq!(a[2], [1e-6, 0.5], "x as a vector: 0.5");
        // cnt: the same value again is not a change: 3 at 0, then 1 at 1 µs.
        let cnt = w.traces[1].points();
        assert_eq!(cnt, &[[0.0, 3.0], [1e-6, 3.0], [1e-6, 1.0], [2e-6, 1.0]]);
    }

    #[test]
    fn clock_frequency() {
        // clk: rising edges at #50 and #150 of 10 ns: period 1 µs → 1 MHz.
        let w = read(SAMPLE.as_bytes()).unwrap();
        let clk = &w.traces[0];
        let r = crate::measure::measure(clk.points(), &(0.0..=2e-6), 0.1);
        let f = r.get(crate::measure::Measurement::Frequency).unwrap();
        assert!((f - 1e6).abs() < 1.0, "{f}");
    }

    #[test]
    fn vendor_names() {
        assert_eq!(vendor_of("Generated by Wokwi.com"), "Wokwi");
        assert_eq!(vendor_of("sigrok 0.5"), "sigrok");
        assert_eq!(vendor_of(""), "VCD");
        let w = read(SAMPLE.as_bytes()).unwrap();
        assert_eq!(w.traces[0].time_step(), Some(1e-8), "the $timescale");
    }

    #[test]
    fn not_vcd() {
        assert_eq!(VcdFormat.probe(b"time,v\n0,1\n"), Confidence::No);
        assert!(read(b"$timescale 1ns $end $enddefinitions $end").is_err());
        assert_eq!(timescale("100 ps"), Some(1e-10));
        assert_eq!(timescale("1us"), Some(1e-6));
    }
}
